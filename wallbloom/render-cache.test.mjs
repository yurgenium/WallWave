import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {defaults, sharpModule} from './core.mjs';
import {initLibrary, imagePath} from './library.mjs';
import {renderDesktop, pruneRendered} from './framing.mjs';

test('render cache reuses unchanged frames, separates monitors and keeps active files', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'wallwave-render-cache-'));
  t.after(() => fs.rm(dir, {recursive: true, force: true}));
  await initLibrary(dir);
  const sharp = await sharpModule();
  sharp.cache(false);
  const item = {id: 'cached', downloaded: true, vote: null};
  await sharp({create: {width: 80, height: 60, channels: 3, background: '#32698a'}}).jpeg().toFile(imagePath(dir, item));
  const first = await renderDesktop(dir, item, defaults, 'left', 80, 60);
  const mtime = (await fs.stat(first)).mtimeMs;
  assert.equal(await renderDesktop(dir, item, {...defaults, maxTotalGB: 0}, 'left', 80, 60), first);
  assert.equal((await fs.stat(first)).mtimeMs, mtime);
  const second = await renderDesktop(dir, item, defaults, 'right', 80, 60);
  assert.notEqual(second, first);
  const changed = await renderDesktop(dir, {...item, frames: {'*': {fit: 'cover', x: 0, y: 0, flip: true}}}, defaults, 'left', 80, 60);
  assert.notEqual(changed, first);
  const ownFile = path.join(dir, 'rendered', 'my-wallpaper.jpg');
  await fs.writeFile(ownFile, 'user file');
  await pruneRendered(dir, [path.basename(first), second]);
  await fs.access(first);
  await fs.access(second);
  await fs.access(ownFile);
  await assert.rejects(fs.access(changed), {code: 'ENOENT'});
  await fs.writeFile(imagePath(dir, item), await sharp({create: {width: 90, height: 70, channels: 3, background: '#ffffff'}}).jpeg().toBuffer());
  assert.notEqual(await renderDesktop(dir, item, defaults, 'left', 80, 60), first);
});
